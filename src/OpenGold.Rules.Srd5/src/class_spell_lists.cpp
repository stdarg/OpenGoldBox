std::vector<std::string> allowed_spells(CharacterClass klass, unsigned level)
{
    std::vector<std::string> result;
    for (const auto &row : class_spell_access)
    {
        if (row.klass == klass && level >= row.min_level)
        {
            result.emplace_back(row.spell);
        }
    }
    return result;
}

bool bard_secret(CharacterClass klass, unsigned level, std::span<const rules::FeatureGrant> grants,
                 std::string_view id)
{
    const bool discovered = std::any_of(grants.begin(), grants.end(),
                                        [&](const auto &g)
                                        {
                                            return g.id == "discovery:" + std::string(id);
                                        });
    static constexpr std::array lists{CharacterClass::cleric, CharacterClass::druid,
                                      CharacterClass::wizard};
    return klass == CharacterClass::bard && (level >= 10 || discovered) &&
           std::any_of(lists.begin(), lists.end(),
                       [&](auto list)
                       {
                           return knows_spell(allowed_spells(list, level), id);
                       });
}
